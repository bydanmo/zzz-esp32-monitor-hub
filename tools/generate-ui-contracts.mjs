import { readFile, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(await readFile(path.join(root, "shared/ui-tokens.json"), "utf8"));
const layouts = JSON.parse(await readFile(path.join(root, "shared/ui-layouts.json"), "utf8"));
const check = process.argv.includes("--check");

const toMacro = (value) => value.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toUpperCase();
const hexNumber = (value) => `0x${value.slice(1).toUpperCase()}`;

const cLines = [
  "#pragma once",
  "",
  "/* Generated by tools/generate-ui-contracts.mjs. Do not edit. */",
  ...Object.entries(tokens.colors).map(([key, value]) => `#define UI_COLOR_${toMacro(key)} ${hexNumber(value)}u`),
  ...Object.entries(tokens.radii).map(([key, value]) => `#define UI_RADIUS_${toMacro(key)} ${value}`),
  ...Object.entries(tokens.fontSizes).map(([key, value]) => `#define UI_FONT_${toMacro(key)} ${value}`),
  ...Object.entries(tokens.motionMs).map(([key, value]) => `#define UI_MOTION_${toMacro(key)}_MS ${value}`),
  ...Object.entries(tokens.freshnessMs).map(([key, value]) => `#define UI_FRESHNESS_${toMacro(key)}_MS ${value}`),
  ...Object.entries(tokens.gesture).map(([key, value]) => `#define UI_GESTURE_${toMacro(key)} ${value}`),
  ""
];

const layoutLines = [
  "#pragma once",
  "",
  "/* Generated by tools/generate-ui-contracts.mjs. Do not edit. */",
  "typedef struct { int x; int y; int width; int height; } ui_rect_t;",
  "",
  ...Object.entries(layouts).flatMap(([section, value]) => {
    if (typeof value.x === "number") {
      return [`static const ui_rect_t UI_LAYOUT_${toMacro(section)} = { ${value.x}, ${value.y}, ${value.width}, ${value.height} };`];
    }
    return Object.entries(value).map(([name, rect]) =>
      `static const ui_rect_t UI_LAYOUT_${toMacro(section)}_${toMacro(name)} = { ${rect.x}, ${rect.y}, ${rect.width}, ${rect.height} };`
    );
  }),
  ""
];

const ts = `// Generated by tools/generate-ui-contracts.mjs. Do not edit.\nexport const uiTokens = ${JSON.stringify(tokens, null, 2)} as const;\nexport const uiLayouts = ${JSON.stringify(layouts, null, 2)} as const;\n`;
const css = `/* Generated by tools/generate-ui-contracts.mjs. Do not edit. */\n:root {\n${Object.entries(tokens.colors).map(([key, value]) => `  --ui-${key.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`)}: ${value};`).join("\n")}\n  --ui-radius-card: ${tokens.radii.card}px;\n  --ui-radius-control: ${tokens.radii.control}px;\n  --ui-motion-press: ${tokens.motionMs.press}ms;\n  --ui-motion-metric: ${tokens.motionMs.metric}ms;\n  --ui-motion-navigation: ${tokens.motionMs.navigation}ms;\n}\n`;

const outputs = [
  ["firmware/main/ui/ui_tokens.generated.h", `${cLines.join("\n")}\n`],
  ["firmware/main/ui/ui_layouts.generated.h", `${layoutLines.join("\n")}\n`],
  ["apps/web/src/design/ui-contracts.generated.ts", ts],
  ["apps/web/src/design/ui-contracts.generated.css", css]
];

let stale = false;
for (const [relativePath, content] of outputs) {
  const outputPath = path.join(root, relativePath);
  if (check) {
    const existing = await readFile(outputPath, "utf8").catch(() => "");
    if (existing !== content) {
      console.error(`Generated UI contract is stale: ${relativePath}`);
      stale = true;
    }
  } else {
    await mkdir(path.dirname(outputPath), { recursive: true });
    await writeFile(outputPath, content, "utf8");
    console.log(`Generated ${relativePath}`);
  }
}

if (stale) process.exitCode = 1;
